/* End-to-end UI checks. Use a separate CLASH_STUDIO_DATA directory and port. */
const fs = require('fs')
const path = require('path')
const assert = require('node:assert/strict')
const runtime = path.join(require('os').homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules')
let playwright
try { playwright = require('playwright') }
catch { playwright = require(require.resolve('playwright', { paths: [runtime, process.cwd()] })) }
const { chromium } = playwright
const base = process.env.STUDIO_TEST_URL || 'http://127.0.0.1:8766'
const root = path.resolve(__dirname, '..')
const out = path.join(root, 'artifacts')
fs.mkdirSync(out, { recursive: true })
const demo = fs.readFileSync(path.join(root, 'examples/demo.yaml'), 'utf8')

;(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true})
  const context = await browser.newContext({viewport: {width: 1440, height: 1040}, acceptDownloads: true})
  const page = await context.newPage()
  page.setDefaultTimeout(10000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('dialog', dialog => dialog.accept())
  try {
    // Clear only this isolated test service through its application API.
    const list = await context.request.get(base + '/api/subscriptions')
    for (const sub of await list.json()) {
      await context.request.delete(`${base}/api/subscriptions/${sub.id}?revision=${sub.revision}`, {headers: {'X-Clash-Studio': '1'}})
    }
    await page.goto(base)
    await page.getByRole('heading', {name:'让订阅，按你的方式运行。'}).waitFor()
    await page.screenshot({path: path.join(out,'welcome-desktop.png'), fullPage: true})
    await page.getByRole('button',{name:'载入演示配置'}).click()
    await page.getByRole('heading',{name:'代理组编排'}).waitFor()
    await page.getByRole('button',{name:'代理节点',exact:false}).click()
    await page.getByRole('textbox',{name:'搜索节点',exact:true}).fill('trojan')
    assert.equal(await page.locator('.node-row').count(),1)
    await page.getByRole('textbox',{name:'搜索节点',exact:true}).fill('')
    const rename = page.getByRole('textbox',{name:'重命名节点 香港 01',exact:true})
    await rename.fill('香港主线')
    await rename.press('Tab')
    await page.getByRole('checkbox',{name:'保留节点 香港 02',exact:true}).uncheck()
    await page.getByRole('button',{name:'代理组',exact:false}).first().click()
    await page.getByRole('button',{name:'新建代理组',exact:true}).click()
    await page.getByPlaceholder('例如：AI 服务').fill('AI 服务')
    await page.getByRole('button',{name:'创建',exact:true}).click()
    await page.getByRole('checkbox',{name:'香港主线 ss',exact:false}).check()
    await page.getByRole('button',{name:'分流规则',exact:false}).click()
    await page.getByRole('textbox',{name:'规则匹配内容'}).fill('openai.com')
    await page.getByLabel('规则目标',{exact:true}).selectOption('AI 服务')
    await page.getByRole('button',{name:'添加规则',exact:true}).click()
    await page.getByRole('button',{name:'下移规则 1',exact:true}).click()
    await page.getByRole('button',{name:'上移规则 2',exact:true}).click()
    await page.getByRole('button',{name:'代理组',exact:false}).first().click()
    await page.locator('.group-card').filter({hasText:'AI 服务'}).click()
    await page.getByRole('textbox',{name:'代理组名称',exact:true}).fill('AI 专用')
    await page.getByRole('textbox',{name:'代理组名称',exact:true}).press('Tab')
    await page.getByText('结构与引用检查通过',{exact:true}).waitFor()
    await page.getByRole('button',{name:'保存并发布',exact:false}).click()
    await page.getByText('修改已保存，本地订阅已更新',{exact:true}).waitFor()
    const summary = (await (await context.request.get(base + '/api/subscriptions')).json())[0]
    let detail = await (await context.request.get(`${base}/api/subscriptions/${summary.id}`)).json()
    let yaml = await (await context.request.get(base + detail.subscription_path)).text()
    assert(yaml.includes('香港主线'))
    assert(!yaml.includes('hk2.example.com'))
    assert(yaml.includes('DOMAIN-SUFFIX,openai.com,AI 专用'))
    assert(yaml.includes('dns:'))
    await page.getByRole('button',{name:'刷新源订阅',exact:true}).click()
    await page.getByText('源订阅已刷新，已重新应用你的修改',{exact:true}).waitFor()
    await page.reload()
    await page.getByRole('button',{name:'代理节点',exact:false}).click()
    assert.equal(await page.getByRole('textbox',{name:'重命名节点 香港 01',exact:true}).inputValue(),'香港主线')
    assert.equal(await page.getByRole('checkbox',{name:'保留节点 香港 02',exact:true}).isChecked(),false)
    await page.getByRole('button',{name:'配置预览',exact:false}).click()
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button',{name:'下载 YAML',exact:true}).click()
    const download = await downloadPromise
    await download.saveAs(path.join(out,'ui-export.yaml'))
    assert(fs.readFileSync(path.join(out,'ui-export.yaml'),'utf8').includes('openai.com'))
    await page.getByRole('button',{name:'版本历史',exact:false}).click()
    assert(await page.getByRole('button',{name:'恢复',exact:true}).count() >= 3)
    await page.getByRole('button',{name:'查看',exact:true}).last().click()
    await page.locator('.history-preview').waitFor()
    await page.getByRole('button',{name:'恢复',exact:true}).last().click()
    await page.getByText('历史版本已恢复',{exact:true}).waitFor()
    detail = await (await context.request.get(`${base}/api/subscriptions/${summary.id}`)).json()
    assert.deepEqual(detail.edits.proxy_renames,{})
    await page.getByRole('button',{name:'代理组',exact:false}).first().click()
    await page.getByRole('textbox',{name:'代理组名称',exact:true}).fill('我的代理')
    await page.getByRole('textbox',{name:'代理组名称',exact:true}).press('Tab')
    await page.getByText('结构与引用检查通过',{exact:true}).waitFor()
    await page.screenshot({path:path.join(out,'editor-desktop.png'),fullPage:true})
    await page.getByRole('button',{name:'撤销未保存修改'}).click()
    await page.getByRole('button',{name:'导入订阅',exact:true}).click()
    await page.getByRole('button',{name:'YAML 文件',exact:true}).click()
    await page.getByLabel('选择 YAML 文件',{exact:true}).setInputFiles({name:'本地测试.yaml',mimeType:'text/yaml',buffer:Buffer.from(demo)})
    await page.getByRole('button',{name:'导入并编辑',exact:true}).click()
    await page.getByRole('heading',{name:'本地测试',exact:true}).waitFor()
    await page.getByLabel('更新源 YAML 文件',{exact:true}).setInputFiles({name:'updated.yaml',mimeType:'text/yaml',buffer:Buffer.from(demo.replaceAll('日本 01','日本 02'))})
    await page.getByText('源订阅已刷新，已重新应用你的修改',{exact:true}).waitFor()
    await page.getByRole('button',{name:'代理节点',exact:false}).click()
    await page.getByRole('textbox',{name:'重命名节点 日本 02',exact:true}).waitFor()
    // Mobile navigation and horizontal overflow check.
    await page.setViewportSize({width:390,height:844})
    await page.getByRole('button',{name:'打开侧栏',exact:true}).click()
    await page.getByRole('button',{name:'示例订阅',exact:false}).click()
    await page.getByRole('button',{name:'代理组',exact:false}).first().click()
    await page.waitForFunction(()=>document.querySelector('.sidebar').getBoundingClientRect().right <= 0)
    await page.screenshot({path:path.join(out,'editor-mobile.png'),fullPage:true})
    assert(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth),'Mobile page overflows horizontally')
    await page.getByRole('button',{name:'打开侧栏',exact:true}).click()
    await page.getByRole('button',{name:'导入订阅',exact:true}).click()
    await page.getByRole('dialog').waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await page.getByRole('dialog').count(),0)
    await page.getByRole('button',{name:'收起侧栏',exact:true}).click()
    await context.grantPermissions(['clipboard-read','clipboard-write'],{origin:base})
    await page.getByRole('button',{name:'复制订阅地址',exact:true}).click()
    assert.equal(await page.evaluate(()=>Promise.race([navigator.clipboard.readText(),new Promise((_,reject)=>setTimeout(()=>reject(new Error('Clipboard read timed out')),5000))])),base+detail.subscription_path)
    await page.getByRole('button',{name:'设置',exact:true}).click()
    await page.getByRole('checkbox',{name:'启用本地订阅地址',exact:true}).uncheck()
    await page.getByRole('button',{name:'保存设置',exact:true}).click()
    await page.getByText('订阅设置已保存',{exact:true}).waitFor()
    assert.equal((await context.request.get(base+detail.subscription_path)).status(),404)
    await page.getByRole('button',{name:'重新生成地址',exact:true}).click()
    await page.getByText('订阅地址已更换，请更新客户端中的地址',{exact:true}).waitFor()
    await page.getByRole('checkbox',{name:'启用本地订阅地址',exact:true}).check()
    await page.getByRole('button',{name:'保存设置',exact:true}).click()
    await page.getByText('订阅设置已保存',{exact:true}).waitFor()
    const rotated = await (await context.request.get(`${base}/api/subscriptions/${summary.id}`)).json()
    assert.notEqual(rotated.subscription_path,detail.subscription_path)
    assert.equal((await context.request.get(base+rotated.subscription_path)).status(),200)
    await page.getByRole('button',{name:'打开侧栏',exact:true}).click()
    await page.getByRole('button',{name:'本地测试',exact:false}).click()
    await page.getByRole('button',{name:'删除订阅',exact:true}).click()
    await page.getByText('订阅已删除',{exact:true}).waitFor()
    assert.equal((await (await context.request.get(base+'/api/subscriptions')).json()).length,1)
    assert.deepEqual(errors,[],'Browser JavaScript exceptions')
    const checks=['demo import','node search','node rename','exclude node','create group','group membership','add rule','rule reorder','rename new group rewrites rule references','publish','refresh preserves edits','persistence after reload','YAML download','history preview and restore','discard draft','file upload','file source refresh','mobile sidebar','mobile layout','keyboard escape','copy subscription URL','disable subscription','rotate subscription URL','enable subscription','delete subscription']
    fs.writeFileSync(path.join(out,'ui-check-result.json'),JSON.stringify({passed:true,checks,browser:'Microsoft Edge headless',errors},null,2))
    console.log(`PASS: ${checks.length} UI workflow checks, desktop and mobile; screenshots in artifacts/`)
  } catch(error) {
    await page.screenshot({path:path.join(out,'ui-failure.png'),fullPage:true}).catch(()=>{})
    throw error
  } finally { await browser.close() }
})().catch(error=>{console.error(error);process.exitCode=1})
